#!/usr/bin/env node
// Generates everything the hub needs from the unchanged sub-extensions in extensions/<id>/:
//   generated/<id>/background.js  the sub-extension's settings.js + background.js inside one function scope
//   generated/<id>/options.html   its options page, loading its own scripts plus the storage shim
//   generated/<id>/ns.js          binds content scripts / options page to the sub-extension's storage namespace
//   background.js                 the hub's service worker (router + every sub-extension)
//   manifest.json                 merged manifest
// Run after copying a new version of a sub-extension into extensions/<id>/:  node tools/build.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(import.meta.url);
const SUBS = require(path.join(root, "hub/subs.js"));
const hubPkg = JSON.parse(fs.readFileSync(path.join(root, "hub/hub.json"), "utf8"));

const rd = (p) => fs.readFileSync(path.join(root, p), "utf8");
const wr = (p, s) => {
  fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
  fs.writeFileSync(path.join(root, p), s);
};
const uniq = (a) => [...new Set(a)];
const HEADER = "// GENERATED by tools/build.mjs - do not edit; change extensions/<id>/ or hub/ and rebuild.\n";

const manifest = {
  manifest_version: 3,
  name: hubPkg.name,
  version: hubPkg.version,
  description: hubPkg.description,
  icons: { 16: "icons/icon16.png", 48: "icons/icon48.png", 128: "icons/icon128.png" },
  action: {
    default_title: hubPkg.actionTitle,
    default_icon: { 16: "icons/icon16.png", 48: "icons/icon48.png", 128: "icons/icon128.png" }
  },
  background: { service_worker: "background.js" },
  options_page: "hub/hub.html",
  permissions: ["storage", "tabs"],
  host_permissions: [],
  optional_host_permissions: [],
  content_scripts: []
};

const swImports = ["hub/subs.js", "hub/storage-ns.js", "hub/router.js"];

for (const sub of SUBS) {
  const dir = `extensions/${sub.id}`;
  const m = JSON.parse(rd(`${dir}/manifest.json`));
  if (m.manifest_version !== 3) throw new Error(`${sub.id}: only manifest v3 is supported`);

  // --- background: settings.js (via importScripts) + background.js in one scope
  const bgFile = m.background && m.background.service_worker;
  if (!bgFile) throw new Error(`${sub.id}: no background.service_worker`);
  const bg = rd(`${dir}/${bgFile}`);
  const imported = [...bg.matchAll(/importScripts\(([^)]*)\)/g)].flatMap((x) =>
    [...x[1].matchAll(/["']([^"']+)["']/g)].map((y) => y[1])
  );
  let out = HEADER + `// Sub-extension "${sub.id}" (${m.name} ${m.version})\n(function () {\n`;
  out += `const chrome = __jfMakeChrome(${JSON.stringify(sub.id)});\n`;
  out += `const importScripts = function () {}; // files below are already included\n`;
  for (const f of imported) out += `\n// ===== ${dir}/${f} =====\n${rd(`${dir}/${f}`)}\n`;
  out += `\n// ===== ${dir}/${bgFile} =====\n${bg}\n})();\n`;
  wr(`generated/${sub.id}/background.js`, out);
  swImports.push(`generated/${sub.id}/background.js`);

  // --- namespace binder
  wr(`generated/${sub.id}/ns.js`, HEADER + `__jfUseNamespace(${JSON.stringify(sub.id)});\n`);

  // --- options page
  if (m.options_page || (m.options_ui && m.options_ui.page)) {
    const opt = m.options_page || m.options_ui.page;
    let html = rd(`${dir}/${opt}`);
    const base = path.posix.join("../../", dir, path.posix.dirname(opt));
    html = html.replace(/\b(src|href)="(?![a-z]+:|#|\/)([^"]+)"/gi, (_, a, p) => `${a}="${path.posix.join(base, p)}"`);
    const shim =
      `<script src="../../hub/storage-ns.js"></script><script src="../../hub/page-shim.js"></script>` +
      `<script src="ns.js"></script>\n`;
    const i = html.search(/<script\b/i);
    if (i < 0) throw new Error(`${sub.id}: options page has no <script>`);
    html = html.slice(0, i) + shim + html.slice(i);
    const note = `<!-- GENERATED by tools/build.mjs from ${dir}/${opt} - do not edit -->\n`;
    const dt = html.match(/^\s*<!doctype[^>]*>\s*/i);
    html = dt ? dt[0] + note + html.slice(dt[0].length) : note + html;
    wr(`generated/${sub.id}/options.html`, html);
  }

  // --- manifest merge
  manifest.permissions.push(...(m.permissions || []));
  manifest.host_permissions.push(...(m.host_permissions || []));
  manifest.optional_host_permissions.push(...(m.optional_host_permissions || []));
  for (const cs of m.content_scripts || []) {
    const js = [];
    if ((cs.js || []).length) js.push("hub/storage-ns.js", "hub/page-shim.js", `generated/${sub.id}/ns.js`);
    js.push(...(cs.js || []).map((f) => `${dir}/${f}`));
    const entry = { ...cs, js };
    if (cs.css) entry.css = cs.css.map((f) => `${dir}/${f}`);
    manifest.content_scripts.push(entry);
  }
}

manifest.permissions = uniq(manifest.permissions);
manifest.host_permissions = uniq(manifest.host_permissions);
manifest.optional_host_permissions = uniq(manifest.optional_host_permissions);
if (!manifest.optional_host_permissions.length) delete manifest.optional_host_permissions;

wr("manifest.json", JSON.stringify(manifest, null, 2) + "\n");
wr("background.js", HEADER + `importScripts(\n${swImports.map((f) => `  ${JSON.stringify(f)}`).join(",\n")}\n);\n`);
console.log(`Built ${SUBS.length} sub-extensions: ${SUBS.map((s) => s.id).join(", ")}`);
